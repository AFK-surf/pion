"""Builds the summary block of results.json and SUMMARY.md from measured data only."""
import statistics

LANGS = ["pion", "moonbit", "rust", "go"]
LANG_NAME = {"pion": "Pion", "moonbit": "MoonBit", "rust": "Rust", "go": "Go"}


def _med(xs):
    xs = [x for x in xs if x is not None]
    return round(statistics.median(xs), 1) if xs else None


def summarize(r):
    out = {}
    d1 = r.get("dim1_tasks", {}).get("tasks", {})
    s1 = {}
    for lang in LANGS:
        ents = [t.get(lang, {}) for t in d1.values()]
        s1[lang] = {
            "implementations": len(ents),
            "pass": sum(1 for e in ents if e.get("pass")),
            "tests_passed": sum(e.get("tests_passed", 0) for e in ents),
            "loc": sum(e.get("metrics", {}).get("loc", 0) for e in ents),
            "bytes": sum(e.get("metrics", {}).get("bytes", 0) for e in ents),
            "est_tokens_bytes_div4": sum(e.get("metrics", {}).get("est_tokens_bytes_div4", 0) for e in ents),
            "lex_tokens": sum(e.get("metrics", {}).get("lex_tokens", 0) for e in ents),
        }
    out["dim1"] = s1

    d2 = r.get("dim2_diagnostics", {}).get("errors", {})
    s2 = {}
    for lang in LANGS:
        ents = [e.get(lang, {}) for e in d2.values()]
        caught = [e for e in ents if e.get("caught_compile_time")]
        s2[lang] = {
            "probes": len(ents),
            "measured": sum(1 for e in ents if e.get("present")),
            "caught_compile_time": len(caught),
            "applicable": sum(1 for e in ents if e.get("applicable", True)),
            "median_check_ms": _med([e.get("latency", {}).get("median_ms") for e in ents]),
            "median_output_bytes_when_caught": _med([e.get("output_bytes") for e in caught]),
            "structured_json_when_caught": "%d/%d" % (sum(1 for e in caught if e.get("structured_json")), len(caught)),
            "with_fixit_when_caught": sum(1 for e in caught if e.get("has_fixit")),
            "machine_applicable_fix_when_caught": sum(1 for e in caught if e.get("machine_applicable_fix")),
            "expectation_mismatches": sum(1 for e in ents if not e.get("matches_expectation", False)),
        }
    out["dim2"] = s2

    d3 = r.get("dim3_loop", {})
    s3 = {}
    for lang in LANGS:
        lp = d3.get("edit_test_loop", {}).get(lang, {})
        ex = d3.get("api_exploration", {}).get(lang, {})
        cc = d3.get("concurrent_worktrees", {}).get(lang, {})
        s3[lang] = {
            "body_edit_test_ms": lp.get("body_edit", {}).get("median_ms"),
            "iface_edit_test_ms": lp.get("iface_edit", {}).get("median_ms"),
            "cold_test_ms": lp.get("cold_test_ms"),
            "api_bytes": ex.get("api_bytes"),
            "api_est_tokens": ex.get("api_est_tokens"),
            "full_source_bytes": ex.get("full_source_bytes"),
            "five_worktrees_wall_ms": cc.get("median_ms"),
            "five_worktrees_in_tree_mb": cc.get("in_tree_mb_total"),
            "five_worktrees_global_cache_mb": cc.get("global_cache_mb"),
        }
    out["dim3"] = s3
    total1 = sum(v["implementations"] for v in s1.values())
    pass1 = sum(v["pass"] for v in s1.values())
    meas2 = sum(v["measured"] for v in s2.values())
    out["gates"] = {
        "dim1_pass": "%d/%d" % (pass1, total1),
        "dim2_measured": "%d/%d" % (meas2, sum(v["probes"] for v in s2.values())),
        "dim2_expectation_mismatches": sum(v["expectation_mismatches"] for v in s2.values()),
    }
    return out


def _fmt(v, suffix=""):
    if v is None:
        return "n/a"
    if isinstance(v, float):
        return ("%.1f" % v) + suffix
    return str(v) + suffix


def _row(cells):
    return "| " + " | ".join(cells) + " |"


def markdown(r):
    s = r["summary"]
    env = r.get("environment", {})
    L = []
    L.append("# Agent-in-the-loop evaluation: Pion vs MoonBit vs Rust vs Go")
    L.append("")
    L.append("Generated by `sh benchmarks/agent_eval/run.sh` at %s on `%s` (%s, %s cores)." % (
        r.get("generated_at_utc"), env.get("host"), env.get("cpu"), env.get("ncpu")))
    L.append("Toolchains: Pion `out/pionc2` (repo %s, %s bytes), %s, %s, %s, %s." % (
        env.get("repo_commit"), env.get("pionc2_bytes"), env.get("moon"), env.get("rustc"), env.get("go"),
        env.get("clang")))
    L.append("Timing protocol: %s. Load average when the report was written: %s "
             "(the station is shared, so absolute milliseconds carry noise; compare ratios, not single digits)." % (
                 r.get("protocol"), r.get("loadavg_at_report")))
    L.append("")
    L.append("Gates: dimension 1 **%s** reference implementations pass (program output equal to `expected.txt` "
             "and the language's own unit tests green); dimension 2 **%s** probes measured, %d expectation mismatches." % (
                 s["gates"]["dim1_pass"], s["gates"]["dim2_measured"], s["gates"]["dim2_expectation_mismatches"]))
    L.append("")

    # ---------------- dim1
    L.append("## 1. Twelve engineering tasks x four languages")
    L.append("")
    L.append(_row(["", "Pion", "MoonBit", "Rust", "Go"]))
    L.append(_row(["---"] * 5))
    for key, label in [("pass", "implementations passing"), ("tests_passed", "unit tests passed"),
                       ("loc", "effective LOC (12 tasks)"), ("bytes", "source bytes"),
                       ("est_tokens_bytes_div4", "est. tokens (bytes/4)"), ("lex_tokens", "lexical tokens")]:
        L.append(_row([label] + [_fmt(s["dim1"][l][key]) for l in LANGS]))
    L.append("")
    d1 = r.get("dim1_tasks", {}).get("tasks", {})
    L.append("Per task: effective LOC / lexical tokens (`✗` marks a failing implementation).")
    L.append("")
    L.append(_row(["task", "Pion", "MoonBit", "Rust", "Go"]))
    L.append(_row(["---"] * 5))
    for t in sorted(d1):
        cells = [t]
        for l in LANGS:
            e = d1[t].get(l, {})
            m = e.get("metrics", {})
            cells.append("%s%s / %s" % ("" if e.get("pass") else "✗ ", m.get("loc", "-"), m.get("lex_tokens", "-")))
        L.append(_row(cells))
    L.append("")

    # ---------------- dim2
    d2 = r.get("dim2_diagnostics", {})
    L.append("## 2. Twelve agent error classes: edit -> check -> diagnose")
    L.append("")
    L.append("Check commands: " + ", ".join("%s `%s`" % (LANG_NAME[l], d2.get("check_commands", {}).get(l, "?"))
                                             for l in LANGS) + ".")
    L.append("")
    L.append(_row(["", "Pion", "MoonBit", "Rust", "Go"]))
    L.append(_row(["---"] * 5))
    for key, label in [("caught_compile_time", "caught before running (of 12)"),
                       ("applicable", "error class expressible"),
                       ("median_check_ms", "median check latency (ms)"),
                       ("median_output_bytes_when_caught", "median diagnostic bytes (caught)"),
                       ("structured_json_when_caught", "caught with JSON diagnostics"),
                       ("with_fixit_when_caught", "caught with any fix suggestion"),
                       ("machine_applicable_fix_when_caught", "caught with a machine-applicable edit")]:
        L.append(_row([label] + [_fmt(s["dim2"][l][key]) for l in LANGS]))
    L.append("")
    L.append("Per probe: `✓` caught at check time / `✗` not caught (`—` not expressible), check latency, diagnostic size, fix suggestion.")
    L.append("")
    L.append(_row(["probe", "Pion", "MoonBit", "Rust", "Go"]))
    L.append(_row(["---"] * 5))
    errs = d2.get("errors", {})
    for k in sorted(errs):
        cells = ["%s<br>%s" % (k, errs[k].get("title", ""))]
        for l in LANGS:
            e = errs[k].get(l, {})
            if not e.get("present"):
                cells.append("missing")
                continue
            mark = "✓" if e.get("caught_compile_time") else ("—" if not e.get("applicable", True) else "✗")
            extra = []
            if e.get("warnings") and not e.get("caught_compile_time"):
                extra.append("%d warning(s)" % e["warnings"])
            if e.get("runtime_race_detector"):
                rd = e["runtime_race_detector"]
                extra.append("`-race`: %s" % ("detected at run time" if rd.get("detected") else "not detected"))
            cells.append("%s %s ms, %s B%s%s" % (
                mark, _fmt(e.get("latency", {}).get("median_ms")), e.get("output_bytes"),
                ", fix-it" if e.get("has_fixit") and e.get("caught_compile_time") else "",
                ("<br>" + "; ".join(extra)) if extra else ""))
        L.append(_row(cells))
    L.append("")
    L.append("First diagnostic line per probe (verbatim, truncated):")
    L.append("")
    for k in sorted(errs):
        L.append("- **%s**" % k)
        for l in LANGS:
            e = errs[k].get(l, {})
            fd = (e.get("first_diagnostic") or "").replace("|", "\\|").replace("\n", " ")
            note = e.get("note") or ""
            fx = (e.get("fixit_sample") or "").replace("|", "\\|").replace("\n", " ")
            L.append("  - %s: %s%s%s" % (LANG_NAME[l], ("`%s`" % fd[:160]) if fd else "(no diagnostic)",
                                           (" — fix: `%s`" % fx[:140]) if fx and e.get("caught_compile_time") else "",
                                           (" — " + note) if note else ""))
    L.append("")

    # ---------------- dim3
    d3 = r.get("dim3_loop", {})
    L.append("## 3. Edit -> test loop, API exploration cost, five concurrent worktrees")
    L.append("")
    L.append("Project: `%s` (three packages: app -> inventory -> shapes). Test commands: %s." % (
        d3.get("project"), ", ".join("%s `%s`" % (LANG_NAME[l], d3.get("test_commands", {}).get(l, "?")) for l in LANGS)))
    L.append("")
    L.append(_row(["", "Pion", "MoonBit", "Rust", "Go"]))
    L.append(_row(["---"] * 5))
    for key, label in [("cold_test_ms", "first (cold) test run, ms"),
                       ("body_edit_test_ms", "private body edit -> tests green, ms"),
                       ("iface_edit_test_ms", "exported-signature edit -> tests green, ms"),
                       ("api_bytes", "API exploration output, bytes"),
                       ("api_est_tokens", "API exploration, est. tokens"),
                       ("full_source_bytes", "reading all sources instead, bytes"),
                       ("five_worktrees_wall_ms", "5 worktrees check+test concurrently (cold), wall ms"),
                       ("five_worktrees_in_tree_mb", "build artefacts inside the 5 worktrees, MB"),
                       ("five_worktrees_global_cache_mb", "shared global cache after the run, MB")]:
        L.append(_row([label] + [_fmt(s["dim3"][l][key]) for l in LANGS]))
    L.append("")
    ex = d3.get("api_exploration", {})
    L.append("API exploration tools: " + "; ".join("%s: %s" % (LANG_NAME[l], ex.get(l, {}).get("api_tool", "?"))
                                                  for l in LANGS) + ".")
    pionx = ex.get("pion", {}).get("extra", {})
    if pionx:
        L.append("Pion alternatives on the same project: plain-text `pionc2 doc` %s B, `query defs --json` %s B, "
                 "`query callers --json` %s B." % (pionx.get("doc_text", {}).get("bytes"),
                                                  pionx.get("query_defs_json", {}).get("bytes"),
                                                  pionx.get("query_callers_json", {}).get("bytes")))
    pionstd = ex.get("pion", {}).get("pion_std_packages", {})
    if pionstd:
        L.append("Pion standard packages: " + "; ".join(
            "`%s` doc --json %s B vs %s B of source" % (k, v.get("doc_json_bytes"), v.get("source_bytes"))
            for k, v in sorted(pionstd.items())) + ".")
    L.append("")
    L.extend(NOTES)
    return "\n".join(L) + "\n"


# Observations made while writing and running the suite (each one reproducible from the
# sources in this directory); kept next to the numbers so neither side is read alone.
NOTES = """## 4. Notes, caveats and observed weaknesses

**Scope of the comparison**
- MoonBit has no shared-memory threads: `t07` / `t08` are single-threaded baselines that compute the same
  chunks sequentially, and probe `e08` cannot be expressed (marked `—`, a sequential analogue is checked).
- Every implementation uses only its language's standard library. Pion uses `std/json` / `std/http` from this
  repository, Go uses `encoding/json` / `net/url`, MoonBit uses `moonbitlang/core/json`; Rust's standard
  library has no JSON, so `t05` carries a hand-written parser (it dominates Rust's `t05` size).
- `t04`: Pion has no trait objects, so its heterogeneous collection is a closed enum wrapper; Rust uses
  `Box<dyn Item>`, MoonBit `&Item`, Go an interface slice.
- Diagnostic sizes are the raw bytes of the JSON/text each command prints. `cargo --message-format=json`
  embeds a pre-rendered human message and artefact records in every line, which is why it is several KB;
  Go and MoonBit print JSON envelopes around plain text messages without fix-its.
- Pion's `fixit` is a natural-language hint attached to every diagnostic, not a span edit; only rustc emits
  machine-applicable replacements (`suggestion_applicability: MachineApplicable`). Both are counted as
  "any fix suggestion"; only rustc's are counted as machine-applicable.
- Go caches test results by test-binary content: when an edit recompiles to an identical binary
  (the body edit folds `n+1 - n` back to `1`), `go test` reports `(cached)` without re-running tests.
  The edits are unique per run, so no content-addressed cache replays an earlier state.
- "First (cold) test run" is a single run in a fresh copy with fresh Pion CAS / Go caches and no warmup
  (OS file caches as they happen to be); the five-worktree figure is the median of 5 runs after a warmup,
  each with fresh worktrees and fresh global caches shared by the five agents. The two are not comparable
  with each other, only across languages.
- The station is shared with other workloads (see the load average above); medians of 5 runs after a warmup
  dampen but do not remove that noise.

**Pion weaknesses found by this suite**
- Fixed after this suite was first run (P15): `opt == Some(x)` used to type-check and compare object
  identity (always false for fresh boxes, hit by the first drafts of `t01` / `t03` tests); `==` / `!=` on
  `Option`, `Result`, structs, arrays, maps, `Bytes`, tuples and payload-carrying enums is now an
  `E_TYPE_MISMATCH` with a `use match` fix-it. A `Result` in statement position (probe `e09`) used to be
  silently discarded; it is now `E_UNHANDLED_RESULT` (`let _ = ...` discards explicitly).
- `pionc2 test <workspace>` runs only the root package's tests; the suite tests each package directory in turn.
- `pionc2 query defs|callers` on a workspace directory returns an empty table; it needs the source files.
- `pionc2 doc --json` is larger than the sources of the small `t06` project (plain-text `pionc2 doc` is compact).
- `debug_assert(...)` is not an expression, so a match arm needs braces around it; there is no
  `String -> Int` parser in the language or its std (`t01` hand-parses digits).

**MoonBit pitfalls met while writing the reference code**
- `String::compare` (and `Bytes::compare`) order by length first, so sorting names needs a byte-order
  comparator (five tasks carry one); `Result` has no `?` operator (checked `raise` is the idiom);
  trait methods from `impl` cannot be called with dot syntax on a concrete type.
""".splitlines()
