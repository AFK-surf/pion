"""Writes deep.pion (4,000+ deep binary trees for check_binary_chain /
qbe_emit_binary_chain) and deep.expected, its reference output computed here
in Python: gen_deep.py <out_dir>."""
import random
import sys

out = sys.argv[1]
rng = random.Random(129)
src = []
exp = []
XS = list(range(-12, 263, 11))

# 1. Left chain of 4,000 `+` / `-` terms.
n = 4000
terms = [(rng.choice("+-"), rng.randint(1, 99)) for _ in range(n)]
src.append("fn left(x : Int) -> Int {\n  x" + "".join(f" {o} {k}" for o, k in terms) + "\n}\n")
def left(x):
    for o, k in terms:
        x = x + k if o == "+" else x - k
    return x

# 2. Right-nested tree of 4,001 levels: x - (k1 - (k2 - (... - x))).
ks = [rng.randint(1, 50) for _ in range(n + 1)]
body = "x"
for k in reversed(ks):
    body = f"({k} - {body})"
src.append(f"fn right(x : Int) -> Int {{\n  x - {body}\n}}\n")
def right(x):
    v = x
    for k in reversed(ks):
        v = k - v
    return x - v

# 3. 1,500 comparisons joined by `&&` / `||` (`&&` binds tighter).
m = 1500
cmps = [("==", rng.randint(-1000, 1000)) if i % 4 == 0 else
        (rng.choice(["<", ">", "!=", "!="]), rng.randint(-20, 280)) for i in range(m)]
ops = [("||" if i % 4 == 3 else "&&") for i in range(m - 1)]
expr = f"x {cmps[0][0]} {cmps[0][1]}"
pexpr = f"x {cmps[0][0]} {cmps[0][1]}"
for o, (c, k) in zip(ops, cmps[1:]):
    expr += f" {o} x {c} {k}"
    pexpr += f" {'and' if o == '&&' else 'or'} x {c} {k}"
src.append(f"fn logic(x : Int) -> Bool {{\n  {expr}\n}}\n")
def logic(x):
    return eval(pexpr, {"x": x})

# 4. String concatenation of 1,200 parts mixing a parameter and literals.
parts = [rng.choice(["s", '"ab"', '"-"', "s", '"\\u{4E2D}"']) for _ in range(1200)]
src.append("fn cat(s : String) -> String {\n  " + " + ".join(parts) + "\n}\n")
def cat(s):
    return "".join(s if p == "s" else {'"ab"': "ab", '"-"': "-", '"\\u{4E2D}"': "中"}[p] for p in parts)

# 5. 300 `?` operands in one `+` chain, leaving at any position; then the
#    same with an owned String left operand.
q = 300
src.append("fn step(i : Int, stop : Int) -> Result[Int, String] {\n"
           "  if i == stop { Err(\"stop\" + i.to_string()) } else { Ok(i % 7) }\n}\n")
src.append("fn chain_try(stop : Int) -> Result[Int, String] {\n  let a : Array[Int] = [stop]\n"
           "  Ok(a.length()" + "".join(f" + step({i}, stop)?" for i in range(q)) + ")\n}\n")
src.append("fn word(i : Int, stop : Int) -> Result[String, String] {\n"
           "  if i == stop { Err(\"word\" + i.to_string()) } else { Ok((i % 10).to_string()) }\n}\n")
src.append("fn str_try(stop : Int) -> Result[String, String] {\n"
           "  Ok((\"p\" + stop.to_string())" + "".join(f" + word({i}, stop)?" for i in range(q)) + ")\n}\n")
def str_try(stop):
    if 0 <= stop < q:
        return f"err word{stop}"
    return "ok p" + str(stop) + "".join(str(i % 10) for i in range(q))

def chain_try(stop):
    if 0 <= stop < q:
        return f"err stop{stop}"
    return "ok " + str(1 + sum(i % 7 for i in range(q)))

src.append("""fn show(r : Result[Int, String]) -> String {
  match r {
    Ok(v) => "ok " + v.to_string()
    Err(e) => "err " + e
  }
}
""")
src.append("""fn shows(r : Result[String, String]) -> String {
  match r {
    Ok(v) => "ok " + v
    Err(e) => "err " + e
  }
}
""")
src.append("""fn bsum(s : String) -> Int {
  let mut t = 0
  let mut i = 0
  while i < s.length() {
    t = t + (i % 13 + 1) * s.code_unit_at(i)
    i = i + 1
  }
  t
}
""")
main = ["fn main(world : World) -> Int {"]
for x in XS:
    main.append(f"  io_println(world, left({x}).to_string() + \" \" + right({x}).to_string() + \" \" + (if logic({x}) {{ \"T\" }} else {{ \"F\" }}))")
    exp.append(f"{left(x)} {right(x)} {'T' if logic(x) else 'F'}")
for s in ["", "x", "éé"]:
    lit = s.replace("é", "\\u{E9}")
    main.append(f"  let c = cat(\"{lit}\")\n  io_println(world, c.length().to_string() + \" \" + bsum(c).to_string())")
    c = cat(s).encode()
    exp.append(f"{len(c)} {sum((i % 13 + 1) * b for i, b in enumerate(c))}")
for stop in [-1, 0, 150, 299, 300]:
    main.append(f"  io_println(world, show(chain_try({stop})))")
    exp.append(chain_try(stop))
    main.append(f"  io_println(world, shows(str_try({stop})))")
    exp.append(str_try(stop))
main.append("  0\n}\n")
src.append("\n".join(main))
open(f"{out}/deep.pion", "w").write("// Generated by tests/e2e/p129_compile_speed_z1/gen_deep.py.\n" + "\n".join(src))
open(f"{out}/deep.expected", "w").write("\n".join(exp) + "\n")
