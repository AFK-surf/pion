"""Writes modpow.pion and its reference output modpow.expected:
gen.py <out_dir>. `x % d == 0` / `!= 0` for every power of two `d` an
8-bit / 32-bit / 64-bit operand type can spell, over all Byte and Int8 values
and boundary values of the wider types, in `if` conditions
(qbe_emit_cond_branch_leaf) and value contexts (qbe_emit_binary_chain)."""
import sys

out = sys.argv[1]
src = []
exp = []

TYPES = [
    # name, literal suffix, bits, signed, sample values
    ("Byte", "", 8, False, None),
    ("Int8", "", 8, True, None),
    ("Int", "", 32, True, [0, 1, -1, 2, -2, 3, 96, -96, 1 << 30, -(1 << 30), (1 << 31) - 1, -(1 << 31), 123456, -123456]),
    ("UInt", "U", 32, False, [0, 1, 2, 3, 96, 1 << 30, (1 << 31), (1 << 32) - 1, 123456]),
    ("Int64", "L", 64, True, [0, 1, -1, 2, -2, 96, -96, 1 << 40, -(1 << 40), (1 << 62), -(1 << 62), (1 << 63) - 1, -(1 << 63), 1234567890123]),
    ("UInt64", "UL", 64, False, [0, 1, 2, 96, 1 << 40, 1 << 62, 1 << 63, (1 << 64) - 1, 1234567890123]),
]

def rem(x, d, signed):
    if not signed:
        return x % d
    r = abs(x) % d
    return -r if x < 0 else r

def lit(t, v):
    name, suf, bits, signed, _ = t
    if name in ("Byte", "Int8"):
        return f"({v}).to_{'byte' if name == 'Byte' else 'int8'}()"
    if signed and v == -(1 << (bits - 1)):
        return f"(0{suf} - {(1 << (bits - 1)) - 1}{suf} - 1{suf})"
    return f"({v}{suf})" if v >= 0 else f"(0{suf} - {-v}{suf})"

main = ["fn main(world : World) -> Int {"]
for t in TYPES:
    name, suf, bits, signed, samples = t
    if samples is None:
        samples = list(range(-128, 128)) if signed else list(range(256))
    maxd = (1 << (bits - 1)) if not signed else (1 << (bits - 2))
    if bits == 8:
        maxd = 128 if not signed else 64
    ds = []
    d = 2
    while d <= maxd:
        ds.append(d)
        d *= 2
    for d in ds:
        fn = f"m_{name.lower()}_{d}"
        # Byte has no integer literals: `b'\xNN'`.
        dl = f"b'\\x{d:02x}'" if name == "Byte" else f"{d}{suf}"
        zl = "b'\\x00'" if name == "Byte" else f"0{suf}"
        src.append(f"fn {fn}(x : {name}) -> Int {{\n"
                   f"  let mut r = 0\n"
                   f"  if x % {dl} == {zl} {{ r = r + 1 }}\n"
                   + (f"  if x % {dl} != {zl} {{ r = r + 2 }}\n" if name == "Int8" else
                      f"  if {zl} != x % {dl} {{ r = r + 2 }}\n") +
                   f"  let b = x % {dl} == {zl}\n"
                   f"  if b {{ r = r + 4 }}\n"
                   f"  r\n}}\n")
    src.append(f"fn sweep_{name.lower()}(world : World, xs : Array[{name}]) -> Unit {{\n" +
               "".join(f"  let mut s{d} = 0\n" for d in ds) +
               "  for x in xs {\n" +
               "".join(f"    s{d} = s{d} * 7 % 1000003 + m_{name.lower()}_{d}(x)\n" for d in ds) +
               "  }\n" +
               f"  io_println(world, \"{name}\"" + "".join(f" + \" \" + s{d}.to_string()" for d in ds) + ")\n}\n")
    arr = "[" + ", ".join(lit(t, v) for v in samples) + "]"
    main.append(f"  let xs_{name.lower()} : Array[{name}] = {arr}")
    main.append(f"  sweep_{name.lower()}(world, xs_{name.lower()})")
    line = name
    for d in ds:
        s = 0
        for v in samples:
            z = rem(v, d, signed) == 0
            r = (1 if z else 0) + (0 if z else 2) + (4 if z else 0)
            s = (s * 7 % 1000003) + r
        line += f" {s}"
    exp.append(line)

# Side effects of the operand happen exactly once, also for Int8 and in a
# value context.
src.append("""fn next_i8(calls : Array[Int]) -> Int8 {
  calls[0] = calls[0] + 1
  (calls[0] * 37 - 100).to_int8()
}

fn next_byte(calls : Array[Int]) -> Byte {
  calls[0] = calls[0] + 1
  (calls[0] * 37).to_byte()
}

fn next_int(calls : Array[Int]) -> Int {
  calls[0] = calls[0] + 1
  calls[0] * 6
}

fn once(world : World) -> Unit {
  let c : Array[Int] = [0]
  let mut hits = 0
  let mut i = 0
  while i < 40 {
    if next_i8(c) % 2 == 0 { hits = hits + 1 }
    if next_byte(c) % b'\\x04' != b'\\x00' { hits = hits + 10 }
    if next_int(c) % 8 == 0 { hits = hits + 100 }
    let b = next_i8(c) % 16 == 0
    if b { hits = hits + 1000 }
    i = i + 1
  }
  io_println(world, "once calls " + c[0].to_string() + " hits " + hits.to_string())
}
""")
c = 0
hits = 0
def wrap8(v, signed):
    v &= 0xFF
    return v - 256 if signed and v >= 128 else v
for i in range(40):
    c += 1; x = wrap8(c * 37 - 100, True)
    if rem(x, 2, True) == 0: hits += 1
    c += 1; x = wrap8(c * 37, False)
    if x % 4 != 0: hits += 10
    c += 1; x = c * 6
    if x % 8 == 0: hits += 100
    c += 1; x = wrap8(c * 37 - 100, True)
    if rem(x, 16, True) == 0: hits += 1000
exp.append(f"once calls {c} hits {hits}")
main.append("  once(world)")
main.append("  0\n}\n")
src.append("\n".join(main))
open(f"{out}/modpow.pion", "w").write("// Generated by tests/e2e/p132_mod_pow2_loop_break/gen.py.\n" + "\n".join(src))
open(f"{out}/modpow.expected", "w").write("\n".join(exp) + "\n")
